// exit 0 service worker: lets the installed web app open and work offline.
//
// Each build is one snapshot: index.html plus every script, stylesheet, data file, font and icon it uses, stored
// under that build's cache name. Scripts and data carry a ?v=<content hash>, so a cached copy is always the right
// one for the page that asks for it.
//   - Online, the page comes from the network, so an update shows up at once.
//   - Offline (or on a very slow connection), the page and its files come from the snapshot: one build, never a mix.
//   - A new build installs in the background and takes over the next time the app is opened. It never swaps files
//     under a page that is already running.
// The package repository under /repo/ and the sync API under /v1/ are never touched.

// BEGIN GENERATED by tools/build.py (do not edit by hand; run the build after changing any file listed here)
const CACHE = "exit0-7747c8b4b0";
const PRECACHE = ["index.html", "css/styles.css?v=5d93f33a91", "js/theme.js?v=b0ad1c5edd", "data/bank.js?v=f2c9d7b431", "data/cards.js?v=3e21669fb2", "data/sheets.js?v=4d72201747", "data/handson.js?v=d4bd125bb1", "data/labindex.js?v=62441ebe33", "js/core.js?v=3439cc311d", "js/sync.js?v=d0f55a3cb5", "js/app.js?v=09ba3e9726", "data/drills.js?v=1f76d363a2", "data/labs.js?v=0f5d61cd0a", "js/man.js?v=bae78eb9af", "js/shell.js?v=ba89e68c31", "manifest.webmanifest", "fonts/figtree-latin-ext-wght-normal.woff2", "fonts/figtree-latin-wght-normal.woff2", "fonts/jetbrains-mono-latin-ext-wght-normal.woff2", "fonts/jetbrains-mono-latin-wght-normal.woff2", "icons/apple-touch-icon.png", "icons/icon-192.png", "icons/icon-512.png", "icons/maskable-512.png"];
// END GENERATED

self.addEventListener("install", e => {
  // cache: "reload" skips the browser's HTTP cache, so the snapshot's index.html is the one this build shipped
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE.map(u => new Request(u, { cache: "reload" })))));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.includes("/repo/") || url.pathname.includes("/v1/")) return;   // package repo and sync API: never cached
  if (req.mode === "navigate") e.respondWith(page(req));
  else if (url.searchParams.has("v") || /\/(fonts|icons)\//.test(url.pathname)) e.respondWith(cacheFirst(req));
  else e.respondWith(networkFirst(req));
});

function withTimeout(promise, ms) {
  return new Promise((resolve, reject) => { const t = setTimeout(() => reject(new Error("timeout")), ms);
    promise.then(r => { clearTimeout(t); resolve(r); }, err => { clearTimeout(t); reject(err); }); });
}
/** The app page: the newest one when online, otherwise the one this snapshot was built with. */
async function page(req) {
  try { return await withTimeout(fetch(req), 4000); }
  catch (err) { const hit = await (await caches.open(CACHE)).match("index.html"); return hit || Response.error(); }
}
/** Files named by content hash, fonts and icons: the cached copy is always right. Anything new is fetched and kept. */
async function cacheFirst(req) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(req);
  if (hit) return hit;
  try { const res = await fetch(req); if (res && res.ok) cache.put(req, res.clone()); return res; }
  catch (err) { return Response.error(); }
}
/** Everything else (the manifest): fresh when online, the cached copy of the same address when not. */
async function networkFirst(req) {
  const cache = await caches.open(CACHE);
  try {
    const res = await withTimeout(fetch(req), 4000);
    if (res && res.ok) cache.put(req, res.clone());
    return res;
  } catch (err) { return (await cache.match(req)) || Response.error(); }
}
