from labs import T, H, LAST, EX, AB, ALL, ANY, HAS, PERMS, MODE, VAR, F, D, HOME, BASE


def trouble(code, obj, lesson_num, title, covers, parts):
    topic = obj.split(".")[0]
    return {"lesson": code, "obj": obj, "num": int(code[1:]), "title": title, "covers": covers, "track": "troubleshoot",
            "url": BASE + "%s/%s/%s_%02d/" % (topic, obj, obj, lesson_num), "parts": parts}


def part(pid, title, intro, tasks, commands, setup=None):
    return {"id": pid, "title": title, "intro": intro, "setup": setup or {}, "commands": commands, "tasks": tasks}


def ROUTE(dst, via=None):
    return {"type": "route", "dst": dst, **({"via": via} if via else {})}


def USER(name, **kw):
    return dict({"type": "user", "name": name}, **kw)


