"""Hands-on labs for the simulated terminal. build.py writes docs/data/labs.js.

There is one lab per LPI Learning Materials lesson (2.1 lesson 1, 2.1 lesson 2, ...), split into short
parts so every command the lesson teaches gets used. The tasks are our own, not copies of the LPI exercises.

Each part has its own fresh machine (setup) and tasks. A task has:
  text      what to do (Markdown-ish: `code`)
  hints     one or more nudges, from vague to nearly the answer (the solution is the last resort)
  solution  the command(s), one per line, as a learner would type them
  check     a declarative test of the machine's state (files, modes, users, processes, variables,
            typed commands, the last output...). Checks don't depend on the simulator, so a real
            Linux backend could evaluate them later.
  explain   shown once the task is done: why it works, plus a real-world tip
  mistakes  optional coaching: {"cmd": regex on the typed line, "out": regex on the output, "say": text,
            "try": an example command that should trigger it (tested)}

tools/test_shell.js runs every solution, requires each check to be false before and true after,
checks every mistake example, and checks that each part uses every command it lists and each
lesson uses every command in its `covers` list."""

BASE = "https://learning.lpi.org/en/learning-materials/010-160/"
HOME = "/home/student"
DEFAULT_PATH = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"


def T(text, hints, solution, check, explain, mistakes=None):
    if isinstance(hints, str):
        hints = [hints]
    t = {"text": text, "hints": hints, "solution": solution, "check": check, "explain": explain}
    if mistakes:
        t["mistakes"] = mistakes
    return t


# ---- check helpers
def H(regex):            return {"type": "history", "regex": regex}
def LAST(regex):         return {"type": "last", "regex": regex}
def CWD(path):           return {"type": "cwd", "path": path}
def EX(path, kind=None): return {"type": "exists", "path": path, **({"kind": kind} if kind else {})}
def AB(path):            return {"type": "absent", "path": path}
def ALL(*c):             return {"type": "all", "checks": list(c)}
def ANY(*c):             return {"type": "any", "checks": list(c)}
def NOT(c):              return {"type": "not", "check": c}
def HAS(path, text=None, regex=None):
    c = {"type": "contains", "path": path}
    if regex is not None:
        c["regex"] = regex
        if regex.startswith("^"): c["flags"] = "m"      # ^ means start of any line in a file
    else: c["text"] = text
    return c
def EQ(path, text):      return {"type": "equals", "path": path, "text": text}
def PERMS(path, perms):  return {"type": "perms", "path": path, "perms": perms}
def MODE(path, mode):    return {"type": "mode", "path": path, "mode": mode}
def VAR(name, value=None, regex=None):
    c = {"type": "var", "name": name}
    if regex is not None: c["regex"] = regex
    elif value is not None: c["value"] = value
    return c
def F(path, data="", **kw): return dict({"path": path, "data": data}, **kw)
def D(path, **kw):          return dict({"path": path, "dir": True}, **kw)


def lesson(code, title, covers, parts):
    obj, n = code.rsplit(".", 1)
    topic = obj.split(".")[0]
    return {"lesson": code, "obj": obj, "num": int(n), "title": title, "covers": covers,
            "url": BASE + "%s/%s/%s_%02d/" % (topic, obj, obj, int(n)), "parts": parts}


def part(pid, title, intro, tasks, commands, setup=None):
    return {"id": pid, "title": title, "intro": intro, "setup": setup or {}, "commands": commands, "tasks": tasks}


